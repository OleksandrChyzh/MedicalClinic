def clean_ukrainian_text(text: str) -> str:
    """Очищення тексту від пунктуації та сміття для TF-IDF."""
    text = text.lower()
    text = re.sub(r'[^а-яіїєґ0-9\s]', ' ', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text

def generate_augmented_dataset():
    dataset = []
    
    # Проходимо по кожному лікарю
    for specialty, symptoms_list in symptoms_base.items():
        for symptom, urgency in symptoms_list:
            # Для кожного симптому застосовуємо різні префікси
            for prefix in prefixes:
                # Формуємо красиву фразу
                full_text = f"{prefix}{symptom}"
                
                # Капіталізуємо першу літеру для сирого тексту
                full_text_formatted = full_text.strip().capitalize()
                cleaned_text = clean_ukrainian_text(full_text_formatted)
                
                dataset.append({
                    "symptom_text": full_text_formatted,
                    "specialty": specialty,
                    "urgency": urgency,
                    "cleaned_text": cleaned_text
                })
                
    # Перетворюємо в DataFrame
    df = pd.DataFrame(dataset)
    
    # Перемішуємо датасет, щоб класи не йшли підряд (важливо для навчання)
    df = df.sample(frac=1, random_state=42).reset_index(drop=True)
    
    # Зберігаємо
    output_path = "triage_dataset.csv"
    df.to_csv(output_path, index=False, encoding='utf-8-sig')
    
    print("================================================================")
    print("🚀 АУГМЕНТАЦІЯ ЗАВЕРШЕНА!")
    print(f"📊 Згенеровано всього рядків: {len(df)}")
    print(f"🏥 Кількість класів (лікарів): {df['specialty'].nunique()}")
    print(f"⚖️ Середня кількість прикладів на клас: {round(len(df) / df['specialty'].nunique(), 1)}")
    print("================================================================")
    
    # Перевіримо баланс класів
    print("\nРозподіл за рівнями терміновості:")
    print(df['urgency'].value_counts())

